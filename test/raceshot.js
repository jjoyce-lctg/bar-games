const { chromium } = require('playwright');
(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1920, height: 1080 } });
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto('file://' + __dirname + '/race.html');
await p.waitForTimeout(1500); await p.screenshot({ path: 'shots/r1-countdown.png' });
await p.waitForTimeout(5000); await p.screenshot({ path: 'shots/r2-mid.png' });
await p.waitForTimeout(6000); await p.screenshot({ path: 'shots/r3-late.png' });
const t=Date.now(); while(!(await p.evaluate(()=>window.done)) && Date.now()-t<30000) await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/r4-finish.png' });
console.log('done', await p.evaluate(()=>window.done), 'errors', errs); await b.close(); })();
